"""Package the Unreal walkthrough as a stand-alone viewer application (no Unreal Editor needed to run it).

    python -m twin.unreal.package [--config Development|Shipping] [--out dist/TwinViewer] [--skip-content] [--zip]

Runs on a DEVELOPER / build machine with Unreal Engine + Visual Studio installed (never on the server):
  1. compiles the editor module (cooking needs it),
  2. creates the viewer's materials and its empty level L_Viewer (scripts/create_viewer_content.py),
  3. RunUAT BuildCookRun: builds the game target, cooks only /Game/Viewer + engine content, stages a pak/IoStore
     build with the prerequisites installer, archives it,
  4. moves debug symbols to <out>/Symbols, adds `Open Twin Viewer.cmd` (launch with a .twinview file),
     README.txt and viewer_build.json,
  5. scans every packaged file for backend secrets (AI key, viewer signing secret, .env) and fails if one is found.

The result in <out>/Windows is what users receive: a folder with TwinWalkthrough.exe.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

from twin.config import ENV_FILE, PROJECT_ROOT, Settings, load_settings, read_env_file
from twin.unreal.runner import SCRIPTS_DIR, UnrealError, _run, compile_template, tail, unreal_paths

DEFAULT_OUT = PROJECT_ROOT / "dist" / "TwinViewer"
EXE = "TwinWalkthrough.exe"
SECRET_PATTERNS = [re.compile(rb"sk-[A-Za-z0-9_\-]{20,}"), re.compile(rb"TWIN_AI_API_KEY\s*="),
                   re.compile(rb"OPENAI_API_KEY\s*="), re.compile(rb"TWIN_VIEWER_SECRET\s*=")]

LAUNCHER = r"""@echo off
rem Open a building in the Twin viewer:  "Open Twin Viewer.cmd" "C:\path\to\Building.twinview"
rem (associate .twinview files with this script to open them by double-click)
setlocal
set HERE=%~dp0
if "%~1"=="" (
  start "" "%HERE%TwinWalkthrough.exe" -windowed -ResX=1600 -ResY=900
) else (
  start "" "%HERE%TwinWalkthrough.exe" -windowed -ResX=1600 -ResY=900 -TwinLaunch="%~f1"
)
"""

README = """Floor Plan Twin - desktop viewer
================================

Walk through buildings generated by the Floor Plan Twin web app. Nothing else needs to be installed
(no Unreal Editor, no Blender). If Windows reports missing runtime libraries, run
Engine\\Extras\\Redist\\en-us\\UEPrereqSetup_x64.exe once.

Open a building
  1. In the web app, open the project, then in "Unreal Engine 5" choose "Open in desktop viewer".
     Your browser downloads <building>.twinview (a short-lived, read-only access link - no password inside).
  2. Drag that file onto "Open Twin Viewer.cmd" (or run:  "Open Twin Viewer.cmd" "<file>.twinview").
     Alternatively start TwinWalkthrough.exe, click "Copy launch code" in the web app and press Ctrl+V.

Controls
  WASD move, mouse look, Shift run, Space jump, F fly, G ghost (through walls), C ceilings on/off
  Left click select (furniture / HVAC details), right click walk there, Tab or 1-9 or M (list) rooms
  V airflow illustration (schematic, not measured, not CFD), B switch building, P screenshot, Esc quit

Data
  The model is downloaded from the backend and cached in TwinWalkthrough\\Saved\\TwinCache (delete freely).
  A model check report is written to TwinWalkthrough\\Saved\\TwinViewer\\validation_<build>.json.
  HVAC values are labelled LIVE BMS (measured) or SIMULATED BMS (demonstration); MATLAB values are simulations.
"""


def create_viewer_content(settings: Settings, log_path: Path, timeout_s: float = 1800) -> dict:
    """Run create_viewer_content.py in the headless editor; returns its report."""
    p = unreal_paths(settings)
    report_path = log_path.with_name("viewer_content_report.json")
    report_path.unlink(missing_ok=True)
    script = (SCRIPTS_DIR / "create_viewer_content.py").as_posix()
    rc = _run([str(p.editor_cmd), str(p.project), "-run=pythonscript", f"-script={script} {report_path.as_posix()}",
               "-unattended", "-nosplash", "-nop4", "-stdout", "-FullStdOutLogOutput"], log_path, timeout_s)
    if not report_path.is_file():
        raise UnrealError("VIEWER_CONTENT_FAILED", f"creating the viewer content produced no report (exit {rc})",
                          {"log_tail": tail(log_path)})
    report = json.loads(report_path.read_text(encoding="utf-8"))
    if report.get("status") != "ok":
        raise UnrealError("VIEWER_CONTENT_FAILED", report.get("error", "failed"), {"trace": report.get("trace", "")})
    return report


def build_cook_run(settings: Settings, config: str, archive: Path, log_path: Path, timeout_s: float = 7200) -> None:
    p = unreal_paths(settings)
    uat = p.engine_dir / "Engine" / "Build" / "BatchFiles" / "RunUAT.bat"
    cmd = ["cmd", "/c", str(uat), f"-ScriptsForProject={p.project}", "BuildCookRun", f"-project={p.project}", "-noP4",
           "-platform=Win64", f"-clientconfig={config}", "-build", "-cook", "-map=/Game/Viewer/L_Viewer", "-stage", "-pak",
           "-iostore", "-compressed", "-prereqs", "-archive", f"-archivedirectory={archive}", "-utf8output", "-unattended",
           "-nocompileeditor"]
    rc = _run(cmd, log_path, timeout_s)
    if rc != 0:
        raise UnrealError("UNREAL_PACKAGE_FAILED", f"BuildCookRun failed (exit {rc})", {"log_tail": tail(log_path, 80)})


def scan_for_secrets(folder: Path, settings: Settings) -> list[str]:
    """Every packaged file is searched for the backend's actual secrets; our own files (the executable, paks,
    configs, launcher) also for key-shaped strings. Epic's unmodified engine binaries under Engine/ are exempt
    from the shape check only (e.g. Vulkan validation-layer ids such as `...sk-SubgroupEqMask-04370`)."""
    needles: list[bytes] = []
    if settings.ai.api_key is not None:
        needles.append(settings.ai.api_key.get_secret_value().encode())
    if settings.viewer_secret is not None:
        needles.append(settings.viewer_secret.get_secret_value().encode())
    key_file = settings.data_dir / "viewer_secret.key"
    if key_file.is_file():
        needles.append(key_file.read_text(encoding="ascii").strip().encode())
    for k, v in read_env_file(ENV_FILE).items():
        if v and len(v) >= 16 and any(w in k for w in ("KEY", "SECRET", "TOKEN")):
            needles.append(v.encode())
    hits: list[str] = []
    for f in folder.rglob("*"):
        if not f.is_file():
            continue
        if f.name == ".env" or f.suffix == ".env":
            hits.append(f"{f.relative_to(folder)}: .env file")
            continue
        data = f.read_bytes()
        for n in needles:
            if n and n in data:
                hits.append(f"{f.relative_to(folder)}: contains a backend secret")
        if f.relative_to(folder).parts[0] == "Engine":
            continue
        for pat in SECRET_PATTERNS:
            if pat.search(data):
                hits.append(f"{f.relative_to(folder)}: matches {pat.pattern!r}")
    return hits


def package(config: str = "Development", out: Path = DEFAULT_OUT, skip_content: bool = False, zip_it: bool = False) -> dict:
    settings = load_settings()
    p = unreal_paths(settings)
    logs = p.project.parent / "Saved" / "Logs"
    t0 = time.time()
    result: dict = {"config": config, "engine": str(p.engine_dir), "project": str(p.project)}
    print("1/5 compiling the editor module ...", flush=True)
    compile_template(settings, logs / "twin_compile.log")
    if not skip_content:
        print("2/5 creating viewer materials + L_Viewer ...", flush=True)
        result["content"] = create_viewer_content(settings, logs / "twin_viewer_content.log")
    archive = out.resolve()
    if archive.exists():
        shutil.rmtree(archive)
    print(f"3/5 BuildCookRun {config} -> {archive} (first run: 20-60 min) ...", flush=True)
    build_cook_run(settings, config, archive, logs / "twin_package.log")
    win = archive / "Windows"
    if not (win / EXE).is_file():
        raise UnrealError("UNREAL_PACKAGE_FAILED", f"{EXE} not found in {win}")
    symbols = archive / "Symbols"  # debug symbols stay with the build machine, not in what users receive
    for pdb in win.rglob("*.pdb"):
        dest = symbols / pdb.relative_to(win)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(pdb), dest)
    print("4/5 adding launcher + README ...", flush=True)
    (win / "Open Twin Viewer.cmd").write_text(LAUNCHER.replace("\n", "\r\n"), encoding="ascii")
    (win / "README.txt").write_text(README.replace("\n", "\r\n"), encoding="utf-8")
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=PROJECT_ROOT, capture_output=True, text=True).stdout.strip()
    info = {"product": "Floor Plan Twin viewer", "config": config, "built_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
            "git_commit": commit or None, "viewer_api": 1, "engine": p.engine_dir.name, "executable": EXE}
    (win / "viewer_build.json").write_text(json.dumps(info, indent=1), encoding="utf-8")
    print("5/5 scanning the package for secrets ...", flush=True)
    hits = scan_for_secrets(win, settings)
    if hits:
        raise UnrealError("SECRET_IN_PACKAGE", "the packaged viewer contains backend secrets; do not distribute it",
                          {"hits": hits[:20]})
    size = sum(f.stat().st_size for f in win.rglob("*") if f.is_file())
    result.update({"folder": str(win), "bytes": size, "files": sum(1 for f in win.rglob("*") if f.is_file()),
                   "secret_scan": "clean", "seconds": round(time.time() - t0, 1)})
    if zip_it:
        result["zip"] = shutil.make_archive(str(archive.parent / f"TwinViewer-{config}"), "zip", win)
    (archive / "package_result.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
    return result


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", choices=["Development", "Shipping"], default="Development")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--skip-content", action="store_true", help="reuse the existing /Game/Viewer content")
    ap.add_argument("--content-only", action="store_true", help="only (re)create /Game/Viewer and stop")
    ap.add_argument("--zip", action="store_true")
    args = ap.parse_args()
    try:
        if args.content_only:
            settings = load_settings()
            logs = unreal_paths(settings).project.parent / "Saved" / "Logs"
            print(json.dumps(create_viewer_content(settings, logs / "twin_viewer_content.log"), indent=1))
            return 0
        res = package(args.config, args.out, args.skip_content, args.zip)
    except UnrealError as exc:
        print(f"FAILED {exc.code}: {exc}")
        for k in ("log_tail", "trace", "hits"):
            if exc.detail.get(k):
                print(exc.detail[k] if isinstance(exc.detail[k], str) else "\n".join(exc.detail[k]))
        return 1
    print(json.dumps(res, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
